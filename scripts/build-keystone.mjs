function annularSector(cx, cy, rInner, rOuter, startDeg, endDeg) {
  const rad = (d) => (d * Math.PI) / 180;
  const pt = (r, d) => [
    +(cx + r * Math.cos(rad(d))).toFixed(4),
    +(cy + r * Math.sin(rad(d))).toFixed(4),
  ];
  const sweep = ((endDeg - startDeg) % 360 + 360) % 360;
  const large = sweep > 180 ? 1 : 0;
  const [x0, y0] = pt(rOuter, startDeg);
  const [x1, y1] = pt(rOuter, endDeg);
  const [x2, y2] = pt(rInner, endDeg);
  const [x3, y3] = pt(rInner, startDeg);
  return `M${x0} ${y0}A${rOuter} ${rOuter} 0 ${large} 1 ${x1} ${y1}L${x2} ${y2}A${rInner} ${rInner} 0 ${large} 0 ${x3} ${y3}Z`;
}

const CX = 16;
const CY = 16;
const R_OUTER = 12.4;
const R_INNER = 6.75;
const GOLD_A = -62;
const GOLD_B = -18;
const GAP = 3.4;

const RING = annularSector(
  CX,
  CY,
  R_INNER,
  R_OUTER,
  GOLD_B + GAP,
  GOLD_A - GAP + 360,
);
const WEDGE = annularSector(CX, CY, R_INNER, R_OUTER, GOLD_A, GOLD_B);

function write(rel, contents) {
  const dest = join(root, rel);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, contents);
}

function markOnly(ringFill, wedgeFill) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32" fill="none" role="img" aria-label="bpulse">
  <path fill="${ringFill}" d="${RING}"/>
  <path fill="${wedgeFill}" d="${WEDGE}"/>
</svg>
`;
}

function plated(size, rx, ringFill = PAPER) {
  const scale = size / 32;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}" fill="none" role="img" aria-label="bpulse">
  <rect width="${size}" height="${size}" rx="${rx}" ry="${rx}" fill="${INK}"/>
  <g transform="scale(${scale})">
    <path fill="${ringFill}" d="${RING}"/>
    <path fill="${GOLD}" d="${WEDGE}"/>
  </g>
</svg>
`;
}

